===============================================
  食堂智慧管理系统 — 安装与使用说明
===============================================

【适用环境】
- 操作系统：麒麟操作系统（Kylin OS）V10 / 统信 UOS / 其他 arm64 架构 Linux
- 硬件架构：arm64（终端执行 uname -m，显示 aarch64 即为 arm64）
- 内存：建议 4GB 以上
- 磁盘空间：安装后约占用 300MB
- 网络：无需互联网，纯局域网环境即可运行

【交付文件】
1. 食堂智慧管理系统-0.0.0-arm64.AppImage      —— 免安装版，双击即用
2. canteen-smart-management_0.0.0_arm64.deb  —— 安装包版，正式安装
3. 安装说明.txt                           —— 本文件

===============================================
  安装方式一：AppImage（免安装，推荐试用）
===============================================

步骤：
1. 将 AppImage 文件复制到电脑任意文件夹
2. 右键点击文件 → 属性 → 权限 → 勾选"允许作为程序执行"
3. 双击运行

首次启动说明：
- 首次启动约需 5-10 秒，系统会自动创建本地数据库
- 启动后会自动加载演示数据，方便您体验各项功能

如果双击无法打开，请打开终端执行：
  chmod +x 食堂智慧管理系统-*.AppImage
  ./食堂智慧管理系统-*.AppImage

===============================================
  安装方式二：deb 安装包（推荐正式部署）
===============================================

步骤：
1. 将 deb 文件复制到电脑
2. 双击安装，或在终端执行：
     sudo dpkg -i canteen-smart-management_*_arm64.deb
3. 如果提示依赖缺失，执行：
     sudo apt-get install -f
4. 安装完成后，在「开始菜单」搜索"食堂智慧管理系统"打开

===============================================
  局域网离线环境说明
===============================================

  无需外网
本系统采用本地 SQLite 数据库设计，所有数据存储在电脑本地，
完全不需要连接互联网。纯局域网环境下可以正常使用所有功能。

  图片显示说明
系统预置的演示数据中包含少量网络图片（菜品照片、监控截图），
在无网环境下这些图片无法加载显示，但：
- 不影响任何功能操作
- 不影响数据录入和查询
- 您自己上传的图片/截图可以正常显示（从本机选择文件）

===============================================
  多终端数据说明
===============================================

每台电脑的数据是独立的，多台电脑之间数据不自动同步。

如需多台电脑共享数据，请使用「备份/恢复」功能：
1. 打开应用，进入「系统设置 → 数据库管理」
2. 点击"备份数据库"导出 .db 文件
3. 在另一台电脑点击"恢复数据库"选择该文件
4. 恢复后需要重启应用生效

===============================================
  首次启动演示数据
===============================================

系统首次启动会自动创建以下演示数据：
- 菜品信息：红烧肉、清炒西兰花、番茄炒蛋等 8 道常见菜品及营养成分
- 供应商：5 家模拟供应商信息
- 验收记录：6 条模拟食材验收记录
- 留样记录：7 条模拟食品留样记录
- AI 识别事件：8 条模拟行为识别告警（未戴口罩、未穿工服等）
- 环境监测：后厨区、就餐大厅等 5 个区域的温湿度/空气质量数据
- 取餐记录：4 个档口及取餐日志
- 公示屏内容：5 条模拟信息发布内容

您可以直接在这些演示数据上操作，熟悉系统后再录入真实数据。

===============================================
  系统功能清单
===============================================

1. 餐饮验收 —— 食材称重、入库、留样管理
2. 环境监测 —— 空气质量、温湿度、异常告警
3. AI 行为识别 —— 未戴口罩、未穿工服、吸烟检测等
4. 信息发布 —— 公示屏内容管理、排版推送
5. 取餐管理 —— 智能餐盘称重、取餐记录统计
6. 数据看板 —— 统计分析、趋势图表、汇总报表

===============================================
  常见问题
===============================================

Q：安装后打不开？
A：确认系统架构为 arm64（uname -m），AppImage 需赋予执行权限，
   deb 包依赖缺失时执行 sudo apt-get install -f

Q：能连外网后数据会上传云端吗？
A：不会。桌面版所有数据仅保存在本地，不涉及云端同步。

Q：如何清空演示数据？
A：进入「系统设置 → 数据库管理 → 清空数据」即可重置。

Q：数据库文件在哪里？
A：数据库保存在 ~/.config/食堂智慧管理系统/canteen.db

